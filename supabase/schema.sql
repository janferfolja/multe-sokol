-- ── Dobrodelne merende, oproščene multe, bonusi (see migrations/003_merende_bonusi.sql) ──
-- 1) Dobrodelna merenda: donations can now be a kasa or a merenda.
alter table public.donations
  add column kind text not null default 'kasa' check (kind in ('kasa', 'merenda'));

-- 2) Oproščene multe: a fine cancelled by a joker stays in the history but counts nowhere.
alter table public.fines
  add column waived boolean not null default false;

-- 3) Bonusi: something good a player did, with a reward.
--    reward_kind 'skip_next' = joker, cancels the player's next multa (used_fine_id = which one).
--    reward_kind 'custom'    = free-text reward; used_at set when it has been redeemed.
create table public.bonuses (
  id            bigint generated by default as identity primary key,
  date          date not null default current_date,
  player_id     bigint not null references public.players on delete cascade,
  reason        text not null,
  reward_kind   text not null default 'custom' check (reward_kind in ('skip_next', 'custom')),
  reward        text,
  used_at       timestamptz,
  used_fine_id  bigint references public.fines on delete set null,
  created_at    timestamptz not null default now(),
  created_by    text default (auth.jwt() ->> 'email'),
  constraint custom_reward_has_text check (reward_kind <> 'custom' or nullif(trim(reward), '') is not null)
);

-- Deleting the fine a joker was used on gives the joker back.
create function public.bonuses_before_update() returns trigger
language plpgsql as $$
begin
  if new.reward_kind = 'skip_next' and old.used_fine_id is not null and new.used_fine_id is null then
    new.used_at := null;
  end if;
  return new;
end $$;

create trigger bonuses_before_update
  before update on public.bonuses
  for each row execute function public.bonuses_before_update();

alter table public.bonuses enable row level security;
create policy "public read" on public.bonuses for select using (true);
create policy "admin write" on public.bonuses for all using (public.is_admin()) with check (public.is_admin());

-- ── Ni prnesu multe penalties + doubling (see migrations/004_ni_prnesu_multe.sql) ──
-- Unpaid multe:
--   after 14 days → a "Ni prnesu multe" penalty fine; penalty_for points to the overdue multa
