-- ── Tables ────────────────────────────────────────────────────────────────

create table public.players (
  id       bigint generated by default as identity primary key,
  name     text not null,
  surname  text not null,
  alias    text,
  year     int,
  club     text,
  active   boolean not null default true
);

create type public.fine_kind as enum ('euro', 'kasa', 'merenda');

create table public.fine_types (
  id      bigint generated by default as identity primary key,
  name    text not null,
  kind    public.fine_kind not null,
  price   numeric(6,2),            -- only for kind = 'euro'
  active  boolean not null default true,
  constraint price_matches_kind check ((kind = 'euro') = (price is not null))
);

create table public.fines (
  id            bigint generated by default as identity primary key,
  player_id     bigint not null references public.players on delete restrict,
  fine_type_id  bigint not null references public.fine_types on delete restrict,
  date          date not null default current_date,
  amount        numeric(6,2),       -- euro snapshot at the time of the fine; null for kasa/merenda
  note          text,
  paid          boolean not null default false,
  paid_at       timestamptz,
  created_at    timestamptz not null default now(),
  created_by    text default (auth.jwt() ->> 'email')
);

create index fines_player_idx on public.fines (player_id);
create index fines_unpaid_idx on public.fines (date) where not paid;

-- Who may write. Add your emails here (see bottom of file).
create table public.admins (
  email text primary key
);

-- ── Fine amount snapshot + paid_at bookkeeping ────────────────────────────

create function public.fines_before_write() returns trigger
language plpgsql as $$
begin
  if tg_op = 'INSERT' and new.amount is null then
    select price into new.amount from public.fine_types where id = new.fine_type_id;
  end if;
  if tg_op = 'UPDATE' and new.fine_type_id <> old.fine_type_id and new.amount is not distinct from old.amount then
    select price into new.amount from public.fine_types where id = new.fine_type_id;
  end if;
  if new.paid and new.paid_at is null then new.paid_at := now(); end if;
  if not new.paid then new.paid_at := null; end if;
  return new;
end $$;

create trigger fines_before_write
  before insert or update on public.fines
  for each row execute function public.fines_before_write();

-- ── Row level security: everyone reads, only admins write ────────────────

create function public.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.admins where email = (auth.jwt() ->> 'email'))
$$;

alter table public.players    enable row level security;
alter table public.fine_types enable row level security;
alter table public.fines      enable row level security;
alter table public.admins     enable row level security;

create policy "public read" on public.players    for select using (true);
create policy "public read" on public.fine_types for select using (true);
create policy "public read" on public.fines      for select using (true);
create policy "admins see admins" on public.admins for select using (public.is_admin());

create policy "admin write" on public.players    for all using (public.is_admin()) with check (public.is_admin());
create policy "admin write" on public.fine_types for all using (public.is_admin()) with check (public.is_admin());
create policy "admin write" on public.fines      for all using (public.is_admin()) with check (public.is_admin());

