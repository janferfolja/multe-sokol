-- Ruleta: every new multa gives the player a coin (🪙); admins can also hand out coins by hand.
-- An admin spends a coin to spin the wheel for the player. Every outcome is about multe and
-- only hits the player who spins; the one time someone else is involved ("pay someone's multa"),
-- they can only gain.
--
-- Coins from multe are not stored: each open multa added in the app is a coin until a spin uses
-- it. Once the multa is paid or forgiven the coin is gone. Imported multe and multe the roulette
-- itself gave never are coins. (Worked out in the app: src/lib/roulette.js, coinsByPlayer.)
-- Safe to run again: it rebuilds the roulette tables (dropping any earlier version of them).

drop table if exists public.roulette_spins;
drop table if exists public.roulette_coins;
drop table if exists public.roulette_outcomes;

-- What the wheel can land on. chance is a percentage; the wheel is shared out by chance.
-- "This multa" = the multa the coin came from (for a hand-given coin: the player's oldest unpaid one).
--   bonus   waive_this  → this multa is forgiven
--           half_this   → this multa costs half (euro multe only)
--           jolly       → the player's next multa is forgiven
--   malus   double_this → this multa counts double
--           extra_fine  → an extra multa of fine_type_id
--           pay_other   → a second wheel picks another player; the spinner pays one of their multe
--   neutral none        → nothing changes
create table public.roulette_outcomes (
  id            bigint generated by default as identity primary key,
  name          text not null check (trim(name) <> ''),
  emoji         text,
  effect        text not null check (effect in ('waive_this', 'half_this', 'jolly', 'double_this', 'extra_fine', 'pay_other', 'none')),
  chance        numeric(6,2) not null default 10 check (chance >= 0 and chance <= 100),
  fine_type_id  bigint references public.fine_types,
  active        boolean not null default true,
  created_at    timestamptz not null default now(),
  constraint extra_fine_has_type check (effect <> 'extra_fine' or fine_type_id is not null)
);

-- Coins handed out by an admin (on top of the ones from multe).
create table public.roulette_coins (
  id          bigint generated by default as identity primary key,
  player_id   bigint not null references public.players on delete cascade,
  reason      text,
  created_at  timestamptz not null default now(),
  created_by  text default (auth.jwt() ->> 'email')
);

-- One row per coin spent, with everything the spin changed (so it can be shown and undone).
-- name/emoji/kind/effect are a snapshot: editing an outcome doesn't rewrite history.
create table public.roulette_spins (
  id               bigint generated by default as identity primary key,
  player_id        bigint not null references public.players on delete cascade,
  outcome_id       bigint references public.roulette_outcomes on delete set null,
  name             text not null,
  emoji            text,
  kind             text not null check (kind in ('bonus', 'malus', 'neutral')),
  effect           text not null,
  fine_id          bigint references public.fines on delete set null,           -- the coin: from this multa…
  coin_id          bigint references public.roulette_coins on delete set null,  -- …or a hand-given coin
  target_fine_id   bigint references public.fines on delete set null,           -- multa forgiven / halved / doubled / paid for
  prev_amount      numeric(6,2),                                                -- amount before halving
  other_player_id  bigint references public.players on delete set null,         -- pay_other: whose multa
  new_fine_id      bigint references public.fines on delete set null,           -- multa the spin added
  bonus_id         bigint references public.bonuses on delete set null,         -- jolly the spin gave
  created_at       timestamptz not null default now(),
  created_by       text default (auth.jwt() ->> 'email')
);

create index roulette_spins_player_idx on public.roulette_spins (player_id);
create unique index roulette_spins_one_per_fine on public.roulette_spins (fine_id) where fine_id is not null;
create unique index roulette_spins_one_per_coin on public.roulette_spins (coin_id) where coin_id is not null;

alter table public.roulette_outcomes enable row level security;
alter table public.roulette_coins    enable row level security;
alter table public.roulette_spins    enable row level security;
create policy "public read" on public.roulette_outcomes for select using (true);
create policy "public read" on public.roulette_coins    for select using (true);
create policy "public read" on public.roulette_spins    for select using (true);
create policy "admin write" on public.roulette_outcomes for all using (public.is_admin()) with check (public.is_admin());
create policy "admin write" on public.roulette_coins    for all using (public.is_admin()) with check (public.is_admin());
create policy "admin write" on public.roulette_spins    for all using (public.is_admin()) with check (public.is_admin());

