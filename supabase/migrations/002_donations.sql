-- Dobrodelni nameni: kase brought voluntarily, not as a fine.
-- They count in the season's Kasa total but not in anyone's number of multe.

create table public.donations (
  id          bigint generated by default as identity primary key,
  date        date not null default current_date,
  player_id   bigint references public.players on delete set null,  -- who brought it (a player)…
  donor_name  text,                                                  -- …or someone else; both empty = anonymous
  quantity    int not null default 1 check (quantity > 0),
  note        text,
  created_at  timestamptz not null default now(),
  created_by  text default (auth.jwt() ->> 'email')
);

alter table public.donations enable row level security;
create policy "public read" on public.donations for select using (true);
create policy "admin write" on public.donations for all using (public.is_admin()) with check (public.is_admin());
