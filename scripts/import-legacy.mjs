// Converts the old site's JSON files (seed/*.json) into:
//   supabase/seed.sql      — run once in Supabase after schema.sql
//   src/lib/demo-data.json — used by demo mode when no Supabase keys are set
// Usage: node scripts/import-legacy.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const read = (f) => JSON.parse(readFileSync(new URL(`../seed/${f}`, import.meta.url)))
const legacyPlayers = read('players.json')
const legacyTypes = read('multe-types.json')
const legacyFines = read('fines-instances.json')

const nd = (v) => (v && v !== 'ND' ? v : null)
const players = legacyPlayers.map((p) => ({
  id: p.id, name: p.name, surname: p.surname, alias: nd(p.alias),
  year: typeof p.year === 'number' ? p.year : null, club: nd(p.club), active: true,
}))

const fineTypes = legacyTypes.map((t) => {
  const kind = typeof t.price === 'number' ? 'euro' : t.price.toLowerCase()
  return { id: t.id, name: t.name, kind, price: kind === 'euro' ? t.price : null, active: true }
})
const typeById = new Map(fineTypes.map((t) => [t.id, t]))

const fines = legacyFines.map((f) => ({
  id: f.id, player_id: f.player_id, fine_type_id: f.multa_id, date: f.date,
  amount: typeById.get(f.multa_id).price, note: f.desc || null,
  paid: f.status === 'Validated', paid_at: f.status === 'Validated' ? `${f.date}T12:00:00Z` : null,
  created_at: `${f.date}T12:00:00Z`, created_by: 'import',
}))

const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replaceAll("'", "''")}'`)
const insert = (table, rows, cols) =>
  `insert into public.${table} (${cols.join(', ')}) overriding system value values\n` +
  rows.map((r) => `  (${cols.map((c) => q(r[c])).join(', ')})`).join(',\n') + ';\n'
const resetSeq = (table) =>
  `select setval(pg_get_serial_sequence('public.${table}', 'id'), (select max(id) from public.${table}));\n`

// Insert fines with the trigger's amount lookup bypassed by passing amount explicitly.
const sql = [
  '-- Generated by scripts/import-legacy.mjs — imports the old multe_sokol data.\n',
  insert('players', players, ['id', 'name', 'surname', 'alias', 'year', 'club', 'active']),
  insert('fine_types', fineTypes, ['id', 'name', 'kind', 'price', 'active']),
  insert('fines', fines, ['id', 'player_id', 'fine_type_id', 'date', 'amount', 'note', 'paid', 'paid_at', 'created_at', 'created_by']),
  resetSeq('players'), resetSeq('fine_types'), resetSeq('fines'),
].join('\n')

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
writeFileSync(new URL('../src/lib/demo-data.json', import.meta.url), JSON.stringify({ players, fineTypes, fines }))
console.log(`players ${players.length}, fine types ${fineTypes.length}, fines ${fines.length}`)
